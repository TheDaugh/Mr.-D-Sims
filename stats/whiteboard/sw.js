/* Offline copy of the stats board. Stale-while-revalidate: a visit shows what is cached and refreshes it in the background,
   so a rebuilt board appears on the second open. Only same-origin GETs are cached; the board's code lives in shared/whiteboard/app/. */
var CACHE = 'mrd-stats-board-v5';
var CORE = ['./', 'index.html', '../../shared/whiteboard/board.css', '../../shared/whiteboard/app/app.js', '../../shared/whiteboard/app/app.css', 'manifest.webmanifest', 'icon.svg'];

self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) { return c.addAll(CORE); }).then(function () { return self.skipWaiting(); }));
});

self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (ks) {
    return Promise.all(ks.filter(function (k) { return k !== CACHE && k.indexOf('mrd-stats-board-') === 0; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});

self.addEventListener('fetch', function (e) {
  var req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(function (c) {
    return c.match(req).then(function (hit) {
      var net = fetch(req).then(function (res) { if (res && res.ok) c.put(req, res.clone()); return res; }).catch(function () { return hit; });
      return hit || net;
    });
  }));
});
