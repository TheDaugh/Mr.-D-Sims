// Reads the lesson boards registered in src/app.jsx (the LESSONS table) and each lesson file's ID, TITLE and FRAMES,
// and returns one list: [{ board, id, title, frames }]. build.mjs writes it to shared/whiteboard/lessons.js for
// teacher/boards.html; tests/unit/board-index.test.js checks the two never drift apart.
import { readFileSync } from 'node:fs';
import path from 'node:path';

export function lessonIndex(here) {
  const app = readFileSync(path.join(here, 'src/app.jsx'), 'utf8');
  const imports = {};
  for (const m of app.matchAll(/import \* as (\w+) from '\.\/lessons\/([\w.-]+)\.js';/g)) imports[m[1]] = m[2];
  const table = (app.match(/var LESSONS = (\{[^\n]*\});/) || [])[1];
  if (!table) throw new Error('LESSONS table not found in app.jsx');
  const out = [];
  for (const b of table.matchAll(/(\w+): \{([^{}]*)\}/g)) {
    for (const e of b[2].matchAll(/'?([\w.]+)'?: (\w+)/g)) {
      const file = imports[e[2]];
      if (!file) throw new Error('No import for ' + e[2]);
      const src = readFileSync(path.join(here, 'src/lessons', file + '.js'), 'utf8');
      const id = (src.match(/export var ID = '([^']+)'/) || [])[1];
      const title = (src.match(/export var TITLE = '([^']+)'/) || [])[1];
      const frames = (src.match(/var FRAMES = \[([^\]]*)\]/) || [])[1];
      if (id !== e[1]) throw new Error(file + ': ID ' + id + ' does not match the LESSONS key ' + e[1]);
      out.push({ board: b[1], id, title, frames: [...frames.matchAll(/'([^']*)'/g)].map((f) => f[1]) });
    }
  }
  return out;
}

export function lessonIndexScript(list) {
  return '/* Generated by tools/whiteboard/build.mjs from src/app.jsx and src/lessons/. Do not edit by hand. */\n' +
    'window.MRD_BOARD_LESSONS = ' + JSON.stringify(list, null, 1) + ';\n';
}
