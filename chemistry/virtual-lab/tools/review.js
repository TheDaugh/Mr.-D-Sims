// Writes content/REVIEW.md for Mr. D to check, and with --gate fails while anything is unverified.
import { writeFileSync } from "node:fs";
import { world, speciesData, reactionData, pairReview } from "../src/engine/load.js";
import { allPairs, resolvePair, pairKey } from "../src/engine/sim.js";
import { isBalanced } from "../src/engine/formula.js";

const rows = [];
const unverifiedSpecies = speciesData.species.filter((s) => !s.verified);
const unverifiedReactions = reactionData.reactions.filter((r) => !r.verified);
const pairs = allPairs(world).map(([a, b]) => {
  const key = pairKey(a, b), res = resolvePair(world, a, b), rev = pairReview.reviewed[key];
  return { key, res, rev };
});
const unreviewed = pairs.filter((p) => !p.rev);

rows.push("# Lab 1 content review\n");
rows.push("Generated by `npm run review`. Check each line against your own knowledge or the cited source, then set `\"verified\": true` in the JSON and add reviewed pairs to `pair-review.json`.\n");
rows.push(`**Status:** ${unverifiedSpecies.length} of ${speciesData.species.length} substances unverified, ${unverifiedReactions.length} of ${reactionData.reactions.length} reactions unverified, ${unreviewed.length} of ${pairs.length} pairs not reviewed.\n`);

rows.push("## Substances\n");
rows.push("| id | name | density g/cm³ | solubility g/100 mL | conducts | verified | source |");
rows.push("|---|---|---|---|---|---|---|");
for (const s of speciesData.species) {
  rows.push(s.phase === "s"
    ? `| ${s.id} | ${s.name} | ${s.density} | ${s.solubility} | ${s.conductivity} | ${s.verified ? "yes" : "NO"} | ${s.source} |`
    : `| ${s.id} | ${s.name} | ${s.density} | (liquid) | | ${s.verified ? "yes" : "NO"} | ${s.source} |`);
}

rows.push("\n## Reactions\n");
rows.push("| id | balanced | rate | what the student sees | verified |");
rows.push("|---|---|---|---|---|");
for (const r of reactionData.reactions) {
  const eq = r.kind === "observation" ? "n/a (color test)" : isBalanced(r) ? "yes" : "NO";
  rows.push(`| ${r.id} | ${eq} | ${r.rateClass || "-"} (${r.rateVerified || "-"}) | ${r.observations.join("; ")} | ${r.verified ? "yes" : "NO"} |`);
}

rows.push("\n## Every pair of stock substances\n");
rows.push("| pair | what the sim says | reviewed |");
rows.push("|---|---|---|");
for (const p of pairs) rows.push(`| ${p.key.replace("+", " + ")} | ${p.res.text} | ${p.rev ? `${p.rev.by} ${p.rev.date}` : "NO"} |`);

writeFileSync(new URL("../content/REVIEW.md", import.meta.url), rows.join("\n") + "\n");
console.log(`REVIEW.md written. Unverified: ${unverifiedSpecies.length} substances, ${unverifiedReactions.length} reactions, ${unreviewed.length} pairs.`);
if (process.argv.includes("--gate") && (unverifiedSpecies.length || unverifiedReactions.length || unreviewed.length)) {
  console.error("GATE FAILED: content is not fully reviewed. Students should not see this lab yet.");
  process.exit(1);
}
